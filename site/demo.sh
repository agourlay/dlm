# ---- split the tape into one plain-text screen per frame -------------------
# Frame 00 is the bare command, held a beat before the run starts.
awk -v dir="$work" '
  function emit(   f, i) {
    f = sprintf("%s/f%02d.txt", dir, ++n)
    for (i = 1; i <= nl; i++) print logs[i] > f
    for (i = 1; i <= nb; i++) print bars[i] > f
    close(f); open = 0
  }
  /^L / { if (open) emit(); logs[++nl] = substr($0, 3); next }
  /^F=$/ { if (open) emit(); open = 1; next }
  /^F$/ { if (open) emit(); open = 1; nb = 0; next }
  /^  / { bars[++nb] = substr($0, 3); next }
  END { if (open) emit() }
' "$work/tape"
: > "$work/f00.txt"

# ---- render ---------------------------------------------------------------
# Colours by line shape, as dlm styles them: timestamps dim, the global bar's
# filled cells plain and its empty cells faint, a download bar cyan where it
# is filled and blue where it is not. The bar glyphs are multi-byte, so the
# faint run is found by literal matches - its first cell, and its last before
# the `pos/len` count - which hold in any locale, where `░*` would not.
colour() {
  sed -e 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g' \
      -e "s|^\(\[[0-9-]* [0-9:]*\]\)|<span foreground=\"$DIM\">\1</span>|" \
      -e "s|░|<span foreground=\"$EMPTY\">░|" \
      -e "s|░ \([0-9]*/[0-9]*\)\$|░</span> \1|" \
      -e "s|\[\(#*\(&gt;\)\{0,1\}\)\(-*\)\]|[<span foreground=\"$CYAN\">\1</span><span foreground=\"$BLUE\">\3</span>]|"
}

prompt="<span foreground=\"$DIM\">\$</span> dlm <span foreground=\"$BLUE\">-i</span> links.txt <span foreground=\"$BLUE\">-m</span> 3"

for f in "$work"/f*.txt; do
  body=$(colour < "$f")
  markup=$(printf '<span font="%s" foreground="%s">%s\n%s</span>' "$FONT" "$TXT" "$prompt" "$body")
  # A fixed-size canvas keeps every frame aligned so the GIF does not jitter.
  magick -background "$BG" -define pango:align=left pango:"$markup" \
         -bordercolor "$BG" -border 28 \
         -background "$BG" -gravity NorthWest -extent 1160x$((ROWS * 23 + 56)) \
         "${f%.txt}.png"
done

# ---- assemble -------------------------------------------------------------
# Hold the bare command a beat, play the run at twice its real speed (a
# frame every half second shown for a quarter), then rest on the report
# before looping. -layers Optimize shrinks the palette/frames for a lean asset.
set -- "$work"/f*.png
first=$1; shift
last=$(eval "printf '%s' \"\${$#}\"")
middle=''
for p in "$@"; do [ "$p" = "$last" ] || middle="$middle $p"; done
# shellcheck disable=SC2086 # the frame list is meant to split
magick -delay 80 "$first" -delay 25 $middle -delay 400 "$last" \
  -loop 0 -layers Optimize "$root/demo.gif"

printf 'wrote %s (%s)\n' "$root/demo.gif" "$(du -h "$root/demo.gif" | cut -f1)"
